const fs = require('fs');
const path = require('path');

const pCode = fs.readFileSync(path.join(__dirname, '../js/products-data.js'), 'utf8');
const wCode = fs.readFileSync(path.join(__dirname, '../js/wholesale.js'), 'utf8');

let PRODUCTS_DATA;
eval(pCode.replace('const PRODUCTS_DATA', 'PRODUCTS_DATA'));

const m = wCode.match(/PRICES:\s*(\{[\s\S]*?\n  \}),/);
const wsPrices = m ? eval('(' + m[1] + ')') : {};

function getBrand(name) {
  const n = name.toUpperCase();
  if (n.startsWith('REIGN')) return 'REIGN';
  if (n.startsWith('U-PENDS')) return 'U-PENDS';
  if (n.startsWith('DOJO')) return 'DOJO';
  if (n.startsWith('AIRMEZ') || n.startsWith('AiRMEZ')) return 'AiRMEZ';
  if (n.startsWith('NIMMBOX') || n.startsWith('NIMBOX')) return 'NIMMBOX';
  if (n.startsWith('BANG')) return 'BANG';
  if (n.startsWith('HOOKALIT')) return 'HOOKALIT';
  if (n.startsWith('HUMO AZUL')) return 'HUMO AZUL';
  if (n.startsWith('BADDIE')) return 'BADDIE BAR';
  if (n.startsWith('DONUT')) return 'DONUT';
  if (n.startsWith('SOLOBAR')) return 'SOLOBAR';
  if (n.startsWith('YOCCO')) return 'YOCCO';
  if (n.startsWith('DEATH ROW')) return 'DEATH ROW';
  if (n.startsWith('LOST MARY')) return 'LOST MARY';
  if (n.startsWith('EASE')) return 'EASE';
  if (n.startsWith('DUMMY')) return 'DUMMY';
  if (n.startsWith('NICKY JAM')) return 'NICKY JAM';
  if (n.startsWith('BEYOND')) return 'BEYOND';
  if (n.startsWith('BUGATTI')) return 'BUGATTI';
  if (n.startsWith('VERA')) return 'VERA';
  if (n.startsWith('KATCHMI')) return 'KATCHMI';
  if (n.startsWith('FIFTY CENT')) return 'FIFTY CENT';
  if (n.startsWith('SPACEMAN')) return 'SPACEMAN';
  if (n.startsWith('DINNER LADY')) return 'DINNER LADY';
  if (n.startsWith('BRASS')) return 'BRASS';
  if (n.startsWith('ANV DIGITAL')) return 'ANV DIGITAL';
  if (n.startsWith('HIGH PRO')) return 'HIGH PRO';
  if (n.startsWith('SECRET PRO')) return 'SECRET PRO';
  if (n.startsWith('WAKA')) return 'WAKA';
  if (n.startsWith('SAMMY') || n.startsWith('SAMI')) return 'SAMMY';
  if (n.startsWith('AIRPODS')) return 'APPLE';
  return name.split(' ')[0] || 'CAPITAL VAPE';
}

function escapeSql(str) {
  if (str === null || str === undefined) return 'NULL';
  return "'" + String(str).replace(/'/g, "''") + "'";
}

let sql = `-- ============================================================================
-- CAPITAL VAPE - CONFIGURACIÓN COMPLETA DE SUPABASE (POSTGRESQL + REALTIME)
-- Ejecutar este archivo completo en el SQL Editor de tu consola de Supabase:
-- https://supabase.com/dashboard/project/gkbzabubivjfzlefcnnq/sql/new
-- ============================================================================

-- 1. EXTENSIONES
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- 2. AJUSTAR / CREAR TABLA products
CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  brand TEXT,
  description TEXT,
  image_url TEXT,
  category TEXT,
  price NUMERIC(12,2) NOT NULL DEFAULT 0,
  price_two_units NUMERIC(12,2),
  wholesale_prices JSONB DEFAULT '{}'::jsonb,
  stock INTEGER NOT NULL DEFAULT 0,
  availability TEXT NOT NULL DEFAULT 'available'
    CHECK (availability IN ('available', 'sold_out', 'discontinued', 'hidden')),
  is_featured BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Agregar columnas adicionales requeridas si no existen
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS slug TEXT UNIQUE;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS subtitulo TEXT DEFAULT '';
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS puffs INTEGER DEFAULT NULL;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS bateria TEXT DEFAULT NULL;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS sabores JSONB DEFAULT '[]'::jsonb;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS colores JSONB DEFAULT '[]'::jsonb;

-- 3. AJUSTAR / CREAR TABLA price_history
CREATE TABLE IF NOT EXISTS public.price_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  old_price NUMERIC(12,2),
  new_price NUMERIC(12,2),
  old_price_two_units NUMERIC(12,2),
  new_price_two_units NUMERIC(12,2),
  old_wholesale_prices JSONB,
  new_wholesale_prices JSONB,
  admin_user TEXT DEFAULT 'Administrador',
  change_reason TEXT,
  changed_by UUID,
  changed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE public.price_history ADD COLUMN IF NOT EXISTS admin_user TEXT DEFAULT 'Administrador';
ALTER TABLE public.price_history ADD COLUMN IF NOT EXISTS change_reason TEXT;

-- 4. CREAR TABLA inventory_history
CREATE TABLE IF NOT EXISTS public.inventory_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  old_stock INTEGER,
  new_stock INTEGER,
  change_reason TEXT,
  admin_user TEXT DEFAULT 'Administrador',
  changed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 5. HABILITAR ROW LEVEL SECURITY (RLS)
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.price_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inventory_history ENABLE ROW LEVEL SECURITY;

-- 6. POLÍTICAS DE LECTURA PÚBLICA (Catálogo visible en tienda)
DROP POLICY IF EXISTS "Public can read visible products" ON public.products;
CREATE POLICY "Public can read visible products"
ON public.products
FOR SELECT
TO public
USING (availability IN ('available', 'sold_out'));

DROP POLICY IF EXISTS "Public can read price history" ON public.price_history;
CREATE POLICY "Public can read price history"
ON public.price_history
FOR SELECT
TO public
USING (true);

DROP POLICY IF EXISTS "Public can read inventory history" ON public.inventory_history;
CREATE POLICY "Public can read inventory history"
ON public.inventory_history
FOR SELECT
TO public
USING (true);

-- 7. ACTIVAR SUPABASE REALTIME
-- Permite que todos los clientes conectados reciban cambios en vivo sin recargar
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' 
      AND schemaname = 'public' 
      AND tablename = 'products'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.products;
  END IF;
END $$;

ALTER TABLE public.products REPLICA IDENTITY FULL;

-- 8. FUNCIONES Y TRIGGERS DE AUDITORÍA AUTOMÁTICA
CREATE OR REPLACE FUNCTION public.log_product_price_and_inventory_changes()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  -- Auditoría de Precios y Promociones
  IF (OLD.price IS DISTINCT FROM NEW.price)
     OR (OLD.price_two_units IS DISTINCT FROM NEW.price_two_units)
     OR (OLD.wholesale_prices::text IS DISTINCT FROM NEW.wholesale_prices::text)
  THEN
    INSERT INTO public.price_history (
      product_id,
      old_price,
      new_price,
      old_price_two_units,
      new_price_two_units,
      old_wholesale_prices,
      new_wholesale_prices,
      admin_user,
      change_reason,
      changed_at
    )
    VALUES (
      NEW.id,
      OLD.price,
      NEW.price,
      OLD.price_two_units,
      NEW.price_two_units,
      OLD.wholesale_prices,
      NEW.wholesale_prices,
      COALESCE(current_setting('app.current_admin_user', true), 'Administrador'),
      COALESCE(current_setting('app.current_change_reason', true), 'Ajuste de precio en panel administrativo'),
      now()
    );
  END IF;

  -- Auditoría de Inventario (Stock)
  IF (OLD.stock IS DISTINCT FROM NEW.stock) THEN
    INSERT INTO public.inventory_history (
      product_id,
      old_stock,
      new_stock,
      change_reason,
      admin_user,
      changed_at
    )
    VALUES (
      NEW.id,
      OLD.stock,
      NEW.stock,
      COALESCE(current_setting('app.current_change_reason', true), 'Actualización de inventario'),
      COALESCE(current_setting('app.current_admin_user', true), 'Administrador'),
      now()
    );
  END IF;

  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS product_price_history_trigger ON public.products;
DROP TRIGGER IF EXISTS trg_audit_product_all_changes ON public.products;

CREATE TRIGGER trg_audit_product_all_changes
BEFORE UPDATE ON public.products
FOR EACH ROW
EXECUTE FUNCTION public.log_product_price_and_inventory_changes();

-- ============================================================================
-- 9. MIGRACIÓN INICIAL DE LOS 40 PRODUCTOS DE CAPITAL VAPE
-- ============================================================================
`;

const insertLines = [];

PRODUCTS_DATA.forEach(p => {
  const brand = getBrand(p.nombre);
  const wp = p.precios_mayoristas || wsPrices[p.id] || {
    "5": Math.round((p.precio || 0) * 0.75),
    "10": Math.round((p.precio || 0) * 0.60),
    "20": Math.round((p.precio || 0) * 0.55),
    "50": Math.round((p.precio || 0) * 0.50),
    "100": Math.round((p.precio || 0) * 0.45)
  };
  const p2 = (p.precio_promo_2 !== undefined && p.precio_promo_2 !== null) ? p.precio_promo_2 : 'NULL';
  const puffs = p.puffs ? p.puffs : 'NULL';
  const bateria = p.bateria ? escapeSql(p.bateria) : 'NULL';
  const availability = p.agotado ? 'sold_out' : 'available';
  const stock = p.stock !== undefined ? p.stock : (p.agotado ? 0 : 50);

  insertLines.push(`(
  ${escapeSql(p.id)},
  ${escapeSql(p.nombre)},
  ${escapeSql(brand)},
  ${escapeSql(p.descripcion || '')},
  ${escapeSql(p.imagen || '')},
  ${escapeSql(p.categoria || 'desechables')},
  ${p.precio || 0},
  ${p2},
  ${escapeSql(JSON.stringify(wp))}::jsonb,
  ${stock},
  ${escapeSql(availability)},
  ${p.recomendado ? 'true' : 'false'},
  ${escapeSql(p.subtitulo || '')},
  ${puffs},
  ${bateria},
  ${escapeSql(JSON.stringify(p.sabores || []))}::jsonb,
  ${escapeSql(JSON.stringify(p.colores || []))}::jsonb
)`);
});

sql += `
INSERT INTO public.products (
  slug, name, brand, description, image_url, category,
  price, price_two_units, wholesale_prices, stock,
  availability, is_featured, subtitulo, puffs, bateria,
  sabores, colores
) VALUES
` + insertLines.join(',\n') + `
ON CONFLICT (slug) DO UPDATE SET
  name = EXCLUDED.name,
  brand = EXCLUDED.brand,
  description = EXCLUDED.description,
  image_url = EXCLUDED.image_url,
  category = EXCLUDED.category,
  price = EXCLUDED.price,
  price_two_units = EXCLUDED.price_two_units,
  wholesale_prices = EXCLUDED.wholesale_prices,
  stock = EXCLUDED.stock,
  availability = EXCLUDED.availability,
  is_featured = EXCLUDED.is_featured,
  subtitulo = EXCLUDED.subtitulo,
  puffs = EXCLUDED.puffs,
  bateria = EXCLUDED.bateria,
  sabores = EXCLUDED.sabores,
  colores = EXCLUDED.colores,
  updated_at = now();
`;

fs.writeFileSync(path.join(__dirname, '../sql/supabase_setup_complete.sql'), sql, 'utf8');
fs.writeFileSync(path.join(__dirname, '../supabase/migrations/20261125172300_capital_vape_complete.sql'), sql, 'utf8');

